import { Circuit } from 'tscircuit';
import { convertCircuitJsonToSchematicSvg } from 'circuit-to-svg';
import { parts, revision } from './model';
import StereoLineIn from './index';
import { mkdir,writeFile,readFile } from 'node:fs/promises';
const out = new URL('./generated/',import.meta.url);
await mkdir(out,{recursive:true});
const circuit = new Circuit({platform:{pcbDisabled:true,partsEngineDisabled:true}});
circuit.add(<StereoLineIn />);
await circuit.renderUntilSettled();
const json = circuit.getCircuitJson();
const aliases = JSON.parse(await readFile(new URL('./pcb/reference-aliases.json',import.meta.url),'utf8'));
const displayJson = json.map(e => e.type === 'source_component' ? {...e,name:aliases[e.name] ?? e.name} : e);
await writeFile(new URL('schematic.svg',out),convertCircuitJsonToSchematicSvg(displayJson));
const errors=json.filter((x)=>/error$/.test(x.type));
await writeFile(new URL('circuit.json',out),JSON.stringify(json,null,2)+'\n');
await writeFile(new URL('netlist.json',out),JSON.stringify({revision,parts},null,2)+'\n');
console.log(JSON.stringify({parts:parts.length,sourceComponents:json.filter((x)=>x.type==='source_component').length,errors},null,2));
if(errors.length) process.exitCode=1;
